const { evaluatePublishedNutrition: evaluate, formatRating } = require('./publishedNutritionScoring');

// Controlled profiles are SYNTHETIC unless explicitly identified as official
// cached calculator examples. No manufacturer nutrition values are fabricated.
function synthetic(values = {}, category = 'general') {
  const units = { energyKj: 'kJ', calories: 'kcal', sodium: 'mg' };
  const all = { energyKj: 0, saturatedFat: 0, totalSugar: 0, sodium: 0, fiber: 0, protein: 0, ...values };
  return { synthetic: true, methodCategory: category, basis: { amount: 100, unit: category === 'beverage' || category === 'water' ? 'ml' : 'g' },
    nutrients: Object.fromEntries(Object.entries(all).map(([key, value]) => [key, { value, unit: units[key] || 'g' }])),
    plantContent: { percent: 0, basis: 'Controlled synthetic composition', source: 'Synthetic reference fixture' } };
}
const code = output => output.reasons.map(reason => reason.code);

describe('original official calculator examples, 2021-09-21 edition', () => {
  // Independently read OOXML cached examples, not generated by this module.
  // Official workbook: Outil_Calcul_Nutri-Score_SpF_EN_20210921.xlsx, row 2
  // in sheets General case / Cheeses / Added fats / Beverages respectively.
  test.each([
    ['average breakfast cereal', 'general', { energyKj: 1676, saturatedFat: 2.4, totalSugar: 26, protein: 8, fiber: 4.8, sodium: 328 }, 0, 15, 10, 'C', 30],
    ['Camembert', 'cheese', { energyKj: 1151, saturatedFat: 13.9, totalSugar: 0, protein: 21, fiber: 0, sodium: 550 }, 0, 19, 14, 'D', 9],
    ['rapeseed oil', 'added-fat', { energyKj: 3780, fat: 100, saturatedFat: 7.3, totalSugar: 0, protein: 0, fiber: 0, sodium: 0 }, 100, 10, 5, 'C', 55],
    ['sweet soft drink', 'beverage', { energyKj: 156, saturatedFat: 0, totalSugar: 8.7, protein: 0.1, fiber: 0, sodium: 36 }, 0, 12, 12, 'E', 0],
  ])('%s matches the official cached raw result and published Yuka conversion', (name, category, nutrients, plant, n, raw, letter, score) => {
    const profile = synthetic(nutrients, category);
    profile.plantContent.percent = plant;
    const result = evaluate(profile);
    expect(result.status).toBe('calculated');
    expect(result.points.negative.possible).toEqual([n]);
    expect(result.rawScore).toBe(raw);
    expect(result.letter).toBe(letter);
    expect(result.nutritionScore100).toBe(score);
  });
});

describe('original threshold conventions', () => {
  test.each([
    [-3, 100], [-2, 100], [-1, 90], [0, 80], [1, 75], [2, 70], [3, 65], [4, 60], [5, 55],
    [6, 50], [7, 45], [8, 40], [9, 35], [10, 30], [11, 15], [12, 13], [13, 11], [14, 9],
    [15, 7], [16, 5], [17, 3], [18, 1], [19, 0], [20, 0],
  ])('published food conversion raw %s becomes %s /100', (raw, expected) => {
    const profile = synthetic(raw < 0 ? { fiber: -raw }
      : { energyKj: raw === 0 ? 0 : Math.min(raw, 10) * 335 + 0.1, saturatedFat: raw > 10 ? raw - 10 + 0.1 : 0 });
    const result = evaluate(profile);
    expect(result.rawScore).toBe(raw); expect(result.nutritionScore100).toBe(expected);
  });
  test.each([
    [-5, 80], [-4, 80], [-3, 77], [-2, 74], [-1, 71], [0, 68], [1, 65], [2, 57],
    [3, 49], [4, 41], [5, 33], [6, 15], [7, 11], [8, 7], [9, 3], [10, 0], [11, 0],
  ])('published beverage conversion raw %s becomes %s /100', (raw, expected) => {
    const profile = synthetic(raw < 0 ? { fiber: -raw }
      : { energyKj: raw === 0 ? 0 : Math.min(raw, 10) * 30 - 0.1, saturatedFat: raw > 10 ? raw - 10 + 0.1 : 0 }, 'beverage');
    const result = evaluate(profile);
    expect(result.rawScore).toBe(raw); expect(result.nutritionScore100).toBe(expected);
  });
  test.each([
    ['energyKj', 'energy', 335, 0], ['energyKj', 'energy', 3350, 9],
    ['totalSugar', 'sugar', 4.5, 0], ['totalSugar', 'sugar', 27, 5], ['totalSugar', 'sugar', 31, 6],
    ['totalSugar', 'sugar', 40, 8], ['saturatedFat', 'saturatedFat', 1, 0], ['saturatedFat', 'saturatedFat', 10, 9],
    ['sodium', 'sodium', 90, 0], ['sodium', 'sodium', 900, 9], ['fiber', 'fiber', 0.9, 0],
    ['fiber', 'fiber', 1.9, 1], ['fiber', 'fiber', 4.7, 4], ['protein', 'protein', 1.6, 0], ['protein', 'protein', 8, 4],
  ])('%s at %s uses strict threshold comparison', (key, pointKey, threshold, lower) => {
    expect(evaluate(synthetic({ [key]: threshold })).points[pointKey].possible).toEqual([lower]);
    expect(evaluate(synthetic({ [key]: threshold + 0.00001 })).points[pointKey].possible).toEqual([lower + 1]);
  });
  test.each([[0, 0], [30, 1], [270, 9]])('beverage energy at %s', (value, expected) => {
    expect(evaluate(synthetic({ energyKj: value }, 'beverage')).points.energy.possible).toEqual([expected]);
    expect(evaluate(synthetic({ energyKj: value + 0.00001 }, 'beverage')).points.energy.possible).toEqual([expected + 1]);
  });
  test.each([[0, 0], [1.5, 1], [13.5, 9]])('beverage sugars at %s', (value, expected) => {
    expect(evaluate(synthetic({ totalSugar: value }, 'beverage')).points.sugar.possible).toEqual([expected]);
    expect(evaluate(synthetic({ totalSugar: value + 0.00001 }, 'beverage')).points.sugar.possible).toEqual([expected + 1]);
  });
  test.each([[10, 1], [16, 2], [64, 10]])('fat ratio equality at %s counts in the higher band', (value, expected) => {
    expect(evaluate(synthetic({ fat: 100, saturatedFat: value }, 'added-fat')).points.saturatedFat.possible).toEqual([expected]);
    expect(evaluate(synthetic({ fat: 100, saturatedFat: value - 0.00001 }, 'added-fat')).points.saturatedFat.possible).toEqual([expected - 1]);
  });
  test.each([[40, 0], [40.04, 0], [40.06, 1], [60, 1], [60.1, 2], [80, 2], [80.1, 5]])('plant %s uses decimal rounding and original bands', (value, expected) => {
    const food = synthetic(); food.plantContent.percent = value;
    expect(evaluate(food).points.plant.possible).toEqual([expected]);
    food.methodCategory = 'beverage'; food.basis.unit = 'ml';
    expect(evaluate(food).points.plant.possible).toEqual([expected * 2]);
  });
  test('high negatives exclude protein unless cheese or maximum eligible plant content', () => {
    const profile = synthetic({ energyKj: 3400, saturatedFat: 2, protein: 12 });
    expect(evaluate(profile).points.proteinApplied.possible).toEqual([0]);
    profile.methodCategory = 'cheese';
    expect(evaluate(profile).points.proteinApplied.possible).toEqual([5]);
    profile.methodCategory = 'general'; profile.plantContent.percent = 81;
    expect(evaluate(profile).points.proteinApplied.possible).toEqual([5]);
  });
  test('beverages need ten plant points to restore protein with high negatives', () => {
    const profile = synthetic({ energyKj: 300, saturatedFat: 2, protein: 12 }, 'beverage');
    profile.plantContent.percent = 70;
    expect(evaluate(profile).points.proteinApplied.possible).toEqual([0]);
    profile.plantContent.percent = 81;
    expect(evaluate(profile).points.proteinApplied.possible).toEqual([5]);
  });
});

describe('normalization, evidence boundaries and uncertainty', () => {
  test('normalizes a serving before official 4.2 energy conversion', () => {
    const profile = synthetic({ energyKj: null, calories: 399 });
    profile.basis.amount = 200;
    expect(evaluate(profile).normalized.nutrients.energyKj).toBe(838);
    expect(evaluate(profile).normalized.nutrients.calories).toBe(199.5);
  });
  test('normalizes mass units and converts salt to rounded sodium', () => {
    const profile = synthetic({ sodium: null, salt: 0.82 });
    profile.nutrients.saturatedFat = { value: 2400, unit: 'mg' };
    const result = evaluate(profile);
    expect(result.normalized.nutrients.sodium).toBe(328);
    expect(result.normalized.nutrients.saturatedFat).toBe(2.4);
  });
  test('preserves direct kJ rather than replacing it with kcal conversion', () => {
    const profile = synthetic({ calories: 399, energyKj: 1669 });
    expect(evaluate(profile).normalized.nutrients.energyKj).toBe(1669);
  });
  test('requires explicit US fluid ounce identity and never equates grams with mL', () => {
    const profile = synthetic({ totalSugar: 10 }, 'beverage');
    profile.basis = { amount: 1, unit: 'fl oz' };
    expect(code(evaluate(profile))).toContain('unsupported-basis');
    profile.basis.system = 'US';
    expect(evaluate(profile).normalized.nutrients.totalSugar).toBeCloseTo(1000 / 29.5735295625, 10);
    profile.basis = { amount: 100, unit: 'g' };
    expect(code(evaluate(profile))).toContain('volume-required');
  });
  test('general liquid foods and added fats accept declared mL', () => {
    const profile = synthetic({ fat: 10, saturatedFat: 1 }, 'added-fat');
    profile.basis.unit = 'ml';
    expect(evaluate(profile).status).toBe('calculated');
    profile.methodCategory = 'general';
    expect(evaluate(profile).status).toBe('calculated');
  });
  test('missing identity, review, source hash and market limit confidence without blocking arithmetic', () => {
    const result = evaluate(synthetic());
    expect(result.status).toBe('calculated');
    expect(result.warnings).toEqual(expect.arrayContaining([expect.stringContaining('GTIN'), expect.stringContaining('Market unknown')]));
    expect(result.grade).toBeNull(); expect(result.scoreReady).toBe(false); expect(result.scanMatchEligible).toBe(false);
  });
  test('known overseas profile remains distinct and does not establish US identity', () => {
    const profile = synthetic(); profile.product = { market: 'GB' };
    expect(evaluate(profile).status).toBe('calculated');
    expect(evaluate(profile).warnings).toContain('This is a non-US profile; it does not establish a US formulation or barcode match.');
    profile.evidence = { market: { claim: 'US' } };
    expect(code(evaluate(profile))).toContain('conflicting-market');
  });
  test('missing added sugar never blocks total-sugar scoring or becomes zero', () => {
    const result = evaluate(synthetic({ totalSugar: 12 }));
    expect(result.status).toBe('calculated');
    expect(result.normalized.nutrients.addedSugar).toBeNull();
  });
  test('missing nutrients stay null and preserve the range of possible outcomes', () => {
    const result = evaluate(synthetic({ protein: null }));
    expect(result.status).toBe('incomplete');
    expect(result.normalized.nutrients.protein).toBeNull();
    expect(result.rawRange).toEqual([-5, 0]);
    expect(result.possibleScores).toEqual([80, 90, 100]);
    expect(result.nutritionScore100).toBeNull();
  });
  test('unknown plant composition cannot silently earn or lose plant credit', () => {
    const profile = synthetic(); delete profile.plantContent;
    const result = evaluate(profile);
    expect(result.normalized.plantPercent).toBeNull();
    expect(result.points.plant.possible).toEqual([0, 1, 2, 5]);
    expect(result.status).toBe('incomplete');
  });
  test('missing fiber may be bounded by declared carbohydrates without inventing fiber', () => {
    const result = evaluate(synthetic({ fiber: null, carbohydrates: 0 }));
    expect(result.normalized.nutrients.fiber).toBeNull();
    expect(result.points.fiber.possible).toEqual([0]);
    expect(result.status).toBe('calculated');
  });
  test('missing saturates are bounded by declared fat while remaining unknown', () => {
    const result = evaluate(synthetic({ saturatedFat: null, fat: 0 }));
    expect(result.normalized.nutrients.saturatedFat).toBeNull();
    expect(result.points.saturatedFat.possible).toEqual([0]);
    expect(result.status).toBe('calculated');
  });
  test('added fats cannot converge by assuming an unknown denominator is positive', () => {
    const result = evaluate(synthetic({ saturatedFat: 0 }, 'added-fat'));
    expect(result.status).toBe('incomplete');
    expect(result.nutritionScore100).toBeNull();
    expect(code(result)).toContain('fat-denominator-unknown');
  });
  test('only emits a number when every retained completion has the same conversion', () => {
    const result = evaluate(synthetic({ fiber: null, protein: 12 }));
    expect(result.normalized.nutrients.fiber).toBeNull();
    expect(result.rawScore).toBeNull(); expect(result.rawRange).toEqual([-10, -5]);
    expect(result.possibleScores).toEqual([100]); expect(result.nutritionScore100).toBe(100);
  });
  test('plain water uses the verified public simulator nutrition exception without inventing a raw score', () => {
    const result = evaluate(synthetic({}, 'water'));
    expect(result.letter).toBe('A'); expect(result.nutritionScore100).toBe(100);
    expect(result.rawScore).toBeNull(); expect(result.rawRange).toBeNull();
    expect(result.possibleScores).toEqual([100]); expect(result.points).toEqual({});
    expect(result.sources.simulator).toBe('https://editor.yuka.io/');
    expect(result.grade).toBeNull(); expect(result.scoreReady).toBe(false);
  });
  test('deterministic, immutable output does not freeze or mutate caller data', () => {
    const profile = synthetic({ protein: 2 }); const before = JSON.stringify(profile);
    const first = evaluate(profile);
    expect(evaluate(profile)).toEqual(first); expect(JSON.stringify(profile)).toBe(before);
    expect(Object.isFrozen(first.normalized.nutrients)).toBe(true);
    expect(Object.isFrozen(profile.nutrients)).toBe(false);
  });
  test.each([[100, '10.0'], [90, '9.0'], [13, '1.3'], [0, '0.0'], [null, null], [101, null], [-1, null]])('formats %s as /10 without conflating the scales', (value, expected) => {
    expect(formatRating(value)).toBe(expected);
  });
});

describe('rejects malformed or contradictory supplied data', () => {
  test.each([
    [p => { p.methodCategory = 'guessed-food'; }, 'unsupported-category'],
    [p => { p.basis.amount = 0; }, 'unsupported-basis'],
    [p => { p.basis.kind = '100ml'; }, 'inconsistent-basis'],
    [p => { p.nutrients.protein.value = -1; }, 'invalid-value'],
    [p => { p.nutrients.protein.value = Infinity; }, 'invalid-value'],
    [p => { p.nutrients.protein.value = '3'; }, 'invalid-value'],
    [p => { p.nutrients.protein.unit = 'ounces'; }, 'unsupported-unit'],
    [p => { p.nutrients.protein = { value: null, unit: 'ounces' }; }, 'unsupported-unit'],
    [p => { p.nutrients.protein = 5; }, 'invalid-measurement'],
    [p => { p.nutrients.protein.basis = { amount: 50, unit: 'g' }; }, 'mixed-measurement-basis'],
    [p => { p.nutrients.addedSugar = { value: 1, unit: 'g' }; }, 'contradictory-nutrients'],
    [p => { p.nutrients.totalSugar.value = null; p.nutrients.addedSugar = { value: 2, unit: 'g' }; p.nutrients.carbohydrates = { value: 1, unit: 'g' }; }, 'contradictory-nutrients'],
    [p => { p.nutrients.totalSugar.value = null; p.nutrients.freeSugar = { value: 2, unit: 'g' }; p.nutrients.carbohydrates = { value: 1, unit: 'g' }; }, 'contradictory-nutrients'],
    [p => { p.nutrients.fat = { value: 0, unit: 'g' }; p.nutrients.saturatedFat.value = 1; }, 'contradictory-nutrients'],
    [p => { p.nutrients.protein.value = 101; }, 'impossible-mass'],
    [p => { p.nutrients.calories = { value: 100, unit: 'kcal' }; }, 'conflicting-energy'],
    [p => { p.nutrients.salt = { value: 1, unit: 'g' }; }, 'conflicting-salt-sodium'],
    [p => { p.sourceState = { unresolvedConflicts: ['different panels'] }; }, 'conflicting-panels'],
    [p => { p.sourceState = { unresolvedConflicts: 'bad shape' }; }, 'invalid-conflicts'],
    [p => { p.source = { id: 'one' }; p.nutrients.protein.sourceId = 'two'; }, 'conflicting-provenance'],
    [p => { p.nutrients.protein.panelId = 'one'; p.nutrients.fiber.panelId = 'two'; }, 'conflicting-provenance'],
    [p => { p.plantContent.percent = 101; }, 'invalid-plant-content'],
    [p => { delete p.plantContent.source; }, 'plant-evidence-missing'],
    [p => { p.methodCategory = 'added-fat'; p.nutrients.fat = { value: 0, unit: 'g' }; }, 'undefined-fat-ratio'],
    [p => { p.methodCategory = 'water'; p.basis.unit = 'ml'; p.nutrients.totalSugar.value = 1; }, 'water-category-conflict'],
  ])('case %# rejects supplied inconsistency', (change, expected) => {
    const profile = synthetic(); change(profile); const result = evaluate(profile);
    expect(result.status).toBe('invalid'); expect(code(result)).toContain(expected);
    expect(result.nutritionScore100).toBeNull(); expect(result.grade).toBeNull(); expect(result.scoreReady).toBe(false);
  });
  test.each(['sugar', 'coconut-sugar', 'honey', 'agave-syrup', 'maple-syrup', 'sweeteners', 'alcohol', 'infant-formula', 'protein-supplement', 'pet-food', 'supplements'])('methodCategory cannot override excluded %s products', category => {
    const profile = synthetic(); profile.product = { category };
    expect(code(evaluate(profile))).toContain('excluded-product-category');
    expect(evaluate(profile).nutritionScore100).toBeNull();
  });
});
